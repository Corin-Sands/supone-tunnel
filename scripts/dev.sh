#!/usr/bin/env bash
# 作者: Corin-Sands
# REGION=china 使用国内构建镜像，其他值使用上游默认。
# 模型地址 / 密钥 / 模型名在应用「设置」里配置。
# 官方 mihomo：打包/编译经 externalBin 内置；设置里仍可再下载更新。不要用 Clash Verge 内核。
# REGION=china 时，构建依赖与内核资源走国内镜像。
set -euo pipefail
cd "$(dirname "$0")/.."
REGION="${REGION:-else}"
export REGION
CARGO_MIRROR="$PWD/.cargo/config.toml"
# 开发态也拉齐 sidecar / GeoIP，避免首次 tauri dev 缺内核或缺 country.mmdb。
node scripts/fetch-mihomo.mjs
node scripts/fetch-geodata.mjs


if [ "$REGION" = "china" ]; then
  export RUSTUP_DIST_SERVER="${RUSTUP_DIST_SERVER:-https://rsproxy.cn}"
  export RUSTUP_UPDATE_ROOT="${RUSTUP_UPDATE_ROOT:-https://rsproxy.cn/rustup}"
  export NPM_CONFIG_REGISTRY="${NPM_CONFIG_REGISTRY:-https://registry.npmmirror.com}"
  mkdir -p "$(dirname "$CARGO_MIRROR")"
  cat >"$CARGO_MIRROR" <<'EOF'
# generated by scripts/dev.sh for REGION=china
[source.crates-io]
replace-with = "rsproxy-sparse"

[source.rsproxy-sparse]
registry = "sparse+https://rsproxy.cn/index/"
EOF
elif [ -f "$CARGO_MIRROR" ] && grep -q "generated by scripts/dev.sh for REGION=china" "$CARGO_MIRROR"; then
  rm -f "$CARGO_MIRROR"
fi

if [ ! -d node_modules ]; then
  npm install
fi
if [ ! -d ui/node_modules ]; then
  npm install --prefix ui
fi
exec npm run dev
